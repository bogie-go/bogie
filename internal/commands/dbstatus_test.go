// assertHint checks that a failure kept the driver's error and put the hint
// on its own line at the end.
func assertHint(t *testing.T, err error, hint, symptom string) {
	t.Helper()
	if err == nil {
		t.Fatal("expected an error")
	}
	msg := err.Error()
	if !strings.Contains(msg, symptom) {
		t.Errorf("err = %v; want the real error to contain %q", err, symptom)
	}
	lines := strings.Split(strings.TrimRight(msg, "\n"), "\n")
	if lines[len(lines)-1] != hint {
		t.Errorf("last line = %q; want hint %q\nfull error:\n%s", lines[len(lines)-1], hint, msg)
	}
}

