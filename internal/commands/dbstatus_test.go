// stopThrowawayPostgres stops the cluster startThrowawayPostgres left
// running. The package already has a TestMain (the stop-signal helper), so
// the cleanup is called from there rather than a second one.
func stopThrowawayPostgres() {
	if pgCleanup != nil {
		pgCleanup()
	}
}

func TestDBStatusReportsTheLiveDatabase(t *testing.T) {
	admin := postgresAdmin(t)
	name := createDatabase(t, admin)
	dbURL := withDatabase(t, admin, name)

	ctx := context.Background()
	conn := connectDB(t, dbURL)
	defer func() { _ = conn.Close(ctx) }()
	mustExec(t, conn, `
		CREATE TABLE goose_db_version (
			id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
			version_id bigint NOT NULL,
			is_applied boolean NOT NULL,
			tstamp timestamp NOT NULL DEFAULT now()
		)`)
	// 20261105010000 was applied and then rolled back: the later row wins,
	// so it is pending and it is not the latest version.
	mustExec(t, conn, `
		INSERT INTO goose_db_version (version_id, is_applied) VALUES
			(0, true),
			(20261105000000, true),
			(20261105010000, true),
			(20261105010000, false)`)
	mustExec(t, conn, `CREATE TABLE posts (id int)`)
	var version string
	if err := conn.QueryRow(ctx, "SELECT current_setting('server_version')").Scan(&version); err != nil {
		t.Fatal(err)
	}
	var rowsBefore int
	if err := conn.QueryRow(ctx, "SELECT count(*) FROM goose_db_version").Scan(&rowsBefore); err != nil {
		t.Fatal(err)
	}

	root := writeApp(t, "blog")
	migrate := filepath.Join(root, "db", "migrate")
	for _, f := range []string{
		"20261105000000_create_posts.sql",
		"20261105010000_add_slug.sql",
		"20261105020000_add_body.sql",
		"20261105030000_in_go.go",
		".keep",
	} {
		if err := os.WriteFile(filepath.Join(migrate, f), []byte("-- +goose Up\n-- +goose Down\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sealDevCredentials(t, root, "database:\n  url: "+dbURL+"\n")
	clearDBEnv(t, "BLOG")

	// From a subdirectory, the same way every other bogie command is run.
	sub := filepath.Join(root, "app", "controllers")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Chdir(sub)

	var out strings.Builder
	if err := DBStatus(nil, &out); err != nil {
		t.Fatalf("DBStatus: %v", err)
	}
	u := mustParseTarget(t, dbURL)
	want := dbReport{
		Host: u.host, Port: u.port, Database: name,
		Postgres: version, Migration: 20261105000000, Pending: 3, Tables: 2,
	}.String()
	if out.String() != want {
		t.Errorf("status =\n%s\nwant\n%s", out.String(), want)
	}

	var rowsAfter int
	if err := conn.QueryRow(ctx, "SELECT count(*) FROM goose_db_version").Scan(&rowsAfter); err != nil {
		t.Fatal(err)
	}
	if rowsAfter != rowsBefore {
		t.Errorf("goose_db_version rows %d -> %d; db:status wrote", rowsBefore, rowsAfter)
	}
}

