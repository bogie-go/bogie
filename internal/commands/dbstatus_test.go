func TestDBStatusUsesTheTestDatabaseOnly(t *testing.T) {
	admin := postgresAdmin(t)
	real := createDatabase(t, admin)
	realURL := withDatabase(t, admin, real)
	decoy := withDatabase(t, admin, "does_not_exist_decoy")

	root := writeApp(t, "blog")
	// The development file and DATABASE_URL both point somewhere else. Test
	// must ignore them, or this connects to a database that is not there.
	sealDevCredentials(t, root, "database:\n  url: "+decoy+"\n")
	clearDBEnv(t, "BLOG")
	t.Setenv("BLOG_ENV", "test")
	t.Setenv("DATABASE_URL", decoy)
	t.Setenv("BLOG_TEST_DATABASE_URL", realURL)
	t.Chdir(root)

	var out strings.Builder
	if err := DBStatus(nil, &out); err != nil {
		t.Fatalf("DBStatus: %v", err)
	}
	if !strings.Contains(out.String(), "database:  "+real+"\n") {
		t.Errorf("status =\n%s\nwant database %s", out.String(), real)
	}
	if strings.Contains(out.String(), "does_not_exist_decoy") {
		t.Errorf("status used a URL test is not allowed to read:\n%s", out.String())
	}
}

