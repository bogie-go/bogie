const updateUsage = `Usage: bogie app:update [--pretend]

Moves the app to this Bogie's layout, the way a generator's update does, but as a
three-way merge: bogie.toml records the version that generated the app, so
what that version generated (base) is rendered again, what this version
generates (theirs) is rendered, and each file on disk (ours, with your
edits) is merged with git merge-file. A file you never touched updates
silently; a file you edited where the template did not merges cleanly; only
a real overlap leaves conflict markers, and the report names those files.

Refuses on a dirty git tree, so the result is one reviewable diff. Files the
templates never produced are not touched: everything bogie g and you wrote
is safe by construction. Afterwards bogie.toml records the new version,
the credentials module is raised if the app's is older, go mod tidy runs, and bogie doctor checks the markers.

Moving across v0.5.0, which moved the app's layers, prints a warning first
(also with --pretend): the per-file merge cannot follow that move.

  --pretend   the report only; nothing written
`

// Settings is what bogie.toml records.
type Settings struct {
	Version string
	Name    string
	Module  string
	Jobs    bool
	// IDScheme is how this app's primary and foreign keys are made. An app
	// from before this setting existed has no "id" line in bogie.toml; it
	// was always uuid, the only scheme there was, so a missing line reads
	// as uuid rather than the newer bigint default.
	IDScheme generate.IDScheme
}

// readSettings parses bogie.toml. The file is five lines the tool wrote
// itself, so this reads exactly that shape and nothing more.
func readSettings(root string) (Settings, error) {
	b, err := os.ReadFile(filepath.Join(root, Marker))
	if err != nil {
		return Settings{}, err
	}
	s := Settings{IDScheme: generate.IDUUID}
	for _, line := range strings.Split(string(b), "\n") {
		key, value, ok := strings.Cut(line, "=")
		if !ok || strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		key, value = strings.TrimSpace(key), strings.Trim(strings.TrimSpace(value), `"`)
		switch key {
		case "bogie":
			s.Version = value
		case "name":
			s.Name = value
		case "module":
			s.Module = value
		case "jobs":
			s.Jobs = value == "true"
		case "id":
			s.IDScheme = generate.IDScheme(value)
		}
	}
	if s.Version == "" || s.Name == "" || s.Module == "" {
		return s, fmt.Errorf("%s: missing bogie, name or module; the file is written by `bogie new` and read as is", Marker)
	}
	if !s.IDScheme.IsValid() {
		return s, fmt.Errorf("%s: id = %q is not bigint or uuid", Marker, s.IDScheme)
	}
	return s, nil
}

// notMerged are files app:update never merges. go.mod and go.sum are
// tidied rather than merged, since `go mod tidy` adds what the new
// templates import and the recorded versions are the app's own (except
// Bogie's own credentials module, raised to the template's version); the marker
// is rewritten, not merged; and the credentials file and its key are made
// by `new` outside the templates, with a random key, so the old version's
// render of them is noise.
var notMerged = map[string]bool{
	"go.mod": true, "go.sum": true, Marker: true,
	"config/master.key": true, "config/credentials.yml.enc": true,
}

// Update handles `bogie app:update`.
func Update(args []string, out io.Writer) error {
	say := func(format string, a ...any) { _, _ = fmt.Fprintf(out, format, a...) }
	fs := flag.NewFlagSet("app:update", flag.ContinueOnError)
	fs.SetOutput(out)
	pretend := fs.Bool("pretend", false, "report what would change and write nothing")
	fs.Usage = func() { say(updateUsage) }
	if err := fs.Parse(args); err != nil {
		return err
	}
	root, err := appRoot(".")
	if err != nil {
		return err
	}
	settings, err := readSettings(root)
	if err != nil {
		return fmt.Errorf("app:update: %w", err)
	}
	current := Version()
	if settings.Version == current {
		say("%12s  %s was generated by this Bogie (%s); nothing to update\n", "identical", settings.Name, current)
		return nil
	}
	if !*pretend {
		if dirty, err := gitDirty(root); err == nil && dirty {
			return fmt.Errorf("app:update: the git tree has uncommitted changes; commit or stash them so the update is one reviewable diff (or --pretend)")
		}
	}

	// A layout move app:update cannot follow: say so before anything runs,
	// and in --pretend too, so the conflict that follows is no surprise.
	crossed := crossesLayoutBreak(settings.Version, current)
	if crossed {
		say("%s", layoutBreakNotice(root, settings, current))
	}

	// theirs: this version's templates, rendered as `new` would.
	theirsDir, err := os.MkdirTemp("", "bogie-theirs-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(theirsDir) }()
	vars := scaffold.Vars{
		Name:          settings.Name,
		Module:        settings.Module,
		EnvPrefix:     strings.ToUpper(settings.Name),
		LayoutVersion: current,
		Jobs:          settings.Jobs,
		IDScheme:      string(settings.IDScheme),
		Mascot:        templates.MascotDataURI(),
	}
	if _, err := scaffold.Render(templates.App, "app", theirsDir, vars, scaffold.Options{}); err != nil {
		return fmt.Errorf("app:update: render: %w", err)
	}
	theirs, err := readTree(theirsDir)
	if err != nil {
		return err
	}

	// base: what the recorded version generated, from the module proxy.
	say("%12s  go run github.com/bogie-go/bogie@%s new %s\n", "run", settings.Version, settings.Name)
	base, baseErr := renderBase(settings, out)
	if baseErr != nil {
		say("%12s  %v\n", "note", baseErr)
		say("%12s  no base to merge against; this is a two-way report and nothing is written\n", "note")
	}

	ours, err := readTree(root)
	if err != nil {
		return err
	}
	results, err := merge(ours, base, theirs, settings.Version, current)
	if err != nil {
		return fmt.Errorf("app:update: %w", err)
	}

	write := !*pretend && baseErr == nil
	warnStale := func() { warnRetired(out, results, ours, base, settings.Version, current) }
	conflicts := 0
	for _, r := range results {
		say("%12s  %s\n", r.op, r.path)
		if r.op == opConflict {
			conflicts++
		}
		if !write || r.content == nil {
			continue
		}
		abs := filepath.Join(root, filepath.FromSlash(r.path))
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			return err
		}
		mode := os.FileMode(0o644)
		if strings.HasPrefix(r.path, "bin/") {
			mode = 0o755
		}
		if err := os.WriteFile(abs, r.content, mode); err != nil {
			return err
		}
	}
	if !write {
		warnStale()
		if baseErr != nil {
			return fmt.Errorf("app:update: could not render what %s generated", settings.Version)
		}
		return nil
	}

	// The marker records the new version; go.mod is tidied, which adds what
	// the new templates import; doctor says whether the markers survived.
	if err := rewriteVersion(root, current); err != nil {
		return err
	}
	say("%12s  %s: bogie = %q\n", "updated", Marker, current)

	// A tool this version pins that the app does not have yet. `go mod tidy`
	// adds what the new templates IMPORT, and a tool directive is imported by
	// nothing, so tidy would leave it out and the tool would be missing the
	// moment something tried to run it: an app that gained .air.toml here
	// without the reload tool serves without reloading and says why.
	for _, tool := range missingTools(theirs["go.mod"], root) {
		say("%12s  go get -tool %s\n", "run", tool)
		if err := goIn(root, out, "get", "-tool", tool); err != nil {
			return fmt.Errorf("app:update: go get -tool %s: %w", tool, err)
		}
	}
	// The credentials module is Bogie's own, and the templates call into it:
	// config.go from v0.3.0 needs credentials.ApplyEnvOverrides, which a v1.5.0
	// go.mod does not have. Every other requirement stays the app's own, but
	// this one is raised to the template's version, or the updated app does not
	// build.
	for _, mod := range staleBogieModules(theirs["go.mod"], root) {
		say("%12s  go get %s\n", "run", mod)
		if err := goIn(root, out, "get", mod); err != nil {
			return fmt.Errorf("app:update: go get %s: %w", mod, err)
		}
	}
	say("%12s  go mod tidy\n", "run")
	if err := goIn(root, out, "mod", "tidy"); err != nil {
		return fmt.Errorf("app:update: go mod tidy: %w", err)
	}
	warnStale()
	if conflicts > 0 {
		say("\n%d file(s) have conflict markers; resolve them, then run bogie doctor and bin/ci.\n", conflicts)
		if crossed {
			say("This is the %s layout move; the steps are at %s\n", layoutBreakVersion, layoutBreakGuide)
		}
		return fmt.Errorf("app:update: %d conflict(s)", conflicts)
	}
	say("\n")
	return Doctor(out)
}

// warnRetired says which files this version no longer generates but the app
// still has. They are never touched: a leftover test can reference a config
// field the new templates dropped and break go vet and bin/ci, and only the
// user can say whether it is theirs now. One line per file, then one hint.
func warnRetired(out io.Writer, results []result, ours, base map[string][]byte, oldVersion, newVersion string) {
	n := 0
	for _, r := range results {
		if r.op != opRetired {
			continue
		}
		state := "edited since generated"
		if bytes.Equal(ours[r.path], base[r.path]) {
			state = "unmodified"
		}
		if n == 0 {
			_, _ = fmt.Fprintln(out)
		}
		n++
		_, _ = fmt.Fprintf(out, "%12s  %s: generated by %s, not by %s; left in place (%s)\n", "WARN", r.path, oldVersion, newVersion, state)
	}
	if n > 0 {
		_, _ = fmt.Fprintf(out, "%12s  nothing was removed; review the file(s) above, and any *_test.go that depends on them (scaffolded model tests may need regenerating), before deleting\n", "hint")
	}
}

// layoutBreakVersion is the first Bogie whose app layout app:update cannot
// merge its way into. v0.5.0 moved app/domain to app/models and the old
// app/models (Store, ids, sqlc output) to db/adapter and db/sqlc, so the
// per-file merge sees retired files and a conflict in app/models/models.go
// (sqlc's output in v0.4, the package doc and errors in v0.5).
const (
	layoutBreakVersion = "v0.5.0"
	layoutBreakGuide   = "https://bogie-go.com/docs/upgrading.html#v0-5"
)

// crossesLayoutBreak reports whether an app recorded at old, moved to
// current, passes layoutBreakVersion. A version it cannot read, such as a
// development build, never counts.
func crossesLayoutBreak(old, current string) bool {
	if _, ok := parseVersion(current); !ok {
		return false
	}
	return versionBefore(old, layoutBreakVersion) && !versionBefore(current, layoutBreakVersion)
}

// layoutBreakNotice is the warning printed before app:update changes
// anything. A uuid app also has app/models/uuid.go, which no template
// produces in either version, so the merge cannot list it as retired; the
// notice does.
func layoutBreakNotice(root string, s Settings, current string) string {
	var b strings.Builder
	f := func(format string, a ...any) { _, _ = fmt.Fprintf(&b, format, a...) }
	f("%12s  %s moved the app's layers, and app:update merges file by file, so it cannot follow:\n", "warning", layoutBreakVersion)
	f("%12s  app/domain becomes app/models; the old app/models becomes db/adapter and db/sqlc.\n", "")
	f("%12s  bogie.toml says %s and this is %s. Expect retired files, a conflict in\n", "", s.Version, current)
	f("%12s  app/models/models.go, and a build that fails until it is resolved.\n", "")
	if s.IDScheme == generate.IDUUID {
		if _, err := os.Stat(filepath.Join(root, "app", "models", "uuid.go")); err == nil {
			f("%12s  app/models/uuid.go (now db/adapter/uuid.go)\n", "retired")
		}
	}
	f("%12s  Steps: %s\n", "", layoutBreakGuide)
	f("%12s  --pretend writes nothing; without it the update goes on in a few seconds (Ctrl-C stops it).\n\n", "")
	return b.String()
}

// versionBefore reports whether version a is older than b, comparing
// major.minor.patch and ranking a pre-release (v0.5.0-rc1, or a pseudo-version
// like v0.4.2-0.2026...) below its release. Build metadata is ignored. A
// version that is not vX.Y.Z is before nothing, and nothing is before it.
func versionBefore(a, b string) bool {
	av, aok := parseVersion(a)
	bv, bok := parseVersion(b)
	if !aok || !bok {
		return false
	}
	for i := 0; i < 3; i++ {
		if av.n[i] != bv.n[i] {
			return av.n[i] < bv.n[i]
		}
	}
	return av.pre && !bv.pre
}

type semver struct {
	n   [3]int
	pre bool
}

func parseVersion(v string) (semver, bool) {
	var out semver
	v, ok := strings.CutPrefix(v, "v")
	if !ok {
		return out, false
	}
	v, _, _ = strings.Cut(v, "+")
	v, pre, hasPre := strings.Cut(v, "-")
	out.pre = hasPre && pre != ""
	parts := strings.Split(v, ".")
	if len(parts) != 3 {
		return out, false
	}
	for i, p := range parts {
		n, err := strconv.Atoi(p)
		if err != nil || n < 0 {
			return out, false
		}
		out.n[i] = n
	}
	return out, true
}

// renderBase runs the recorded version's `new` into a temp dir and reads
// the tree it made. Any pushed commit is a version the module proxy can
// serve, so a development build's apps can update too; a +dirty build's
// cannot, and says so.
func renderBase(s Settings, out io.Writer) (map[string][]byte, error) {
	if strings.Contains(s.Version, "dirty") {
		return nil, fmt.Errorf("%s was built from uncommitted changes, which no module proxy can serve", s.Version)
	}
	dir, err := os.MkdirTemp("", "bogie-base-")
	if err != nil {
		return nil, err
	}
	defer func() { _ = os.RemoveAll(dir) }()
	args := []string{"run", "github.com/bogie-go/bogie@" + s.Version, "new", s.Name, "--module=" + s.Module, "--skip-tidy"}
	if s.Jobs {
		args = append(args, "--jobs")
	}
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	var stderr bytes.Buffer
	cmd.Stdout = io.Discard
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if i := strings.LastIndex(msg, "\n"); i >= 0 {
			msg = msg[i+1:]
		}
		return nil, fmt.Errorf("go run bogie@%s: %s", s.Version, msg)
	}
	return readTree(filepath.Join(dir, s.Name))
}

// readTree reads every file under root into a map by slash path, skipping
// .git and build output, which no template produces.
func readTree(root string) (map[string][]byte, error) {
	out := map[string][]byte{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			if rel == ".git" || rel == "tmp" {
				return filepath.SkipDir
			}
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		out[rel] = b
		return nil
	})
	return out, err
}

type op string

const (
	opIdentical op = "identical" // ours already is theirs
	opUpdated   op = "updated"   // ours was base; now theirs
	opMerged    op = "merged"    // ours and theirs both changed, cleanly
	opConflict  op = "conflict"  // both changed the same lines; markers left
	opCreate    op = "create"    // new in this version
	opKept      op = "kept"      // the template changed nothing, or you deleted the file
	opRetired   op = "retired"   // no longer generated and still on disk; left as it is
)

type result struct {
	path    string
	op      op
	content []byte // what to write, or nil for nothing
}

// merge decides every template-produced file. With no base (nil), the
// report is two-way: identical or conflict, and nothing is written.
func merge(ours, base, theirs map[string][]byte, oldVersion, newVersion string) ([]result, error) {
	paths := map[string]bool{}
	for p := range theirs {
		paths[p] = true
	}
	for p := range base {
		paths[p] = true
	}
	var sorted []string
	for p := range paths {
		if !notMerged[p] {
			sorted = append(sorted, p)
		}
	}
	sortStrings(sorted)

	var results []result
	for _, p := range sorted {
		o, inOurs := ours[p]
		b, inBase := base[p]
		t, inTheirs := theirs[p]
		switch {
		case !inTheirs:
			// The template is gone. The file is the user's now; one the user
			// already deleted is nothing to report.
			if inOurs {
				results = append(results, result{p, opRetired, nil})
			}
		case !inOurs && inBase:
			// Generated before and deleted by the user, like welcome.go.
			results = append(results, result{p, opKept, nil})
		case !inOurs:
			results = append(results, result{p, opCreate, t})
		case bytes.Equal(o, t):
			results = append(results, result{p, opIdentical, nil})
		case base == nil:
			results = append(results, result{p, opConflict, nil})
		case !inBase:
			// Old base had no such file but ours does: the user made one of
			// the same name. Theirs can only be offered as a conflict.
			merged, n, err := mergeFile(o, nil, t, oldVersion, newVersion)
			if err != nil {
				return nil, err
			}
			_ = n
			results = append(results, result{p, opConflict, merged})
		case bytes.Equal(o, b):
			results = append(results, result{p, opUpdated, t})
		case bytes.Equal(b, t):
			results = append(results, result{p, opKept, nil})
		default:
			merged, conflicts, err := mergeFile(o, b, t, oldVersion, newVersion)
			if err != nil {
				return nil, err
			}
			if conflicts > 0 {
				results = append(results, result{p, opConflict, merged})
			} else {
				results = append(results, result{p, opMerged, merged})
			}
		}
	}
	return results, nil
}

// mergeFile is `git merge-file -p ours base theirs`: the merged text, and
// how many conflict hunks it left.
func mergeFile(ours, base, theirs []byte, oldVersion, newVersion string) ([]byte, int, error) {
	dir, err := os.MkdirTemp("", "bogie-merge-")
	if err != nil {
		return nil, 0, err
	}
	defer func() { _ = os.RemoveAll(dir) }()
	paths := []string{filepath.Join(dir, "ours"), filepath.Join(dir, "base"), filepath.Join(dir, "theirs")}
	for i, content := range [][]byte{ours, base, theirs} {
		if content == nil {
			content = []byte{}
		}
		if err := os.WriteFile(paths[i], content, 0o644); err != nil {
			return nil, 0, err
		}
	}
	cmd := exec.Command("git", "merge-file", "-p",
		"-L", "yours", "-L", "bogie "+oldVersion, "-L", "bogie "+newVersion,
		paths[0], paths[1], paths[2])
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err = cmd.Run()
	var exitErr *exec.ExitError
	switch {
	case err == nil:
		return stdout.Bytes(), 0, nil
	case errors.As(err, &exitErr) && exitErr.ExitCode() > 0:
		// A positive exit status is the number of conflicts.
		return stdout.Bytes(), exitErr.ExitCode(), nil
	default:
		return nil, 0, fmt.Errorf("git merge-file: %v: %s", err, strings.TrimSpace(stderr.String()))
	}
}

// rewriteVersion sets the bogie line of the marker to the new version.
func rewriteVersion(root, version string) error {
	path := filepath.Join(root, Marker)
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	lines := strings.Split(string(b), "\n")
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "bogie ") || strings.HasPrefix(strings.TrimSpace(l), "bogie=") {
			lines[i] = fmt.Sprintf("bogie = %q", version)
		}
	}
	return os.WriteFile(path, []byte(strings.Join(lines, "\n")), 0o644)
}

// rewriteJobs sets the jobs line of the marker, as enableJobs does once it
// has merged in what --jobs adds.
func rewriteJobs(root string, on bool) error {
	path := filepath.Join(root, Marker)
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	lines := strings.Split(string(b), "\n")
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "jobs ") || strings.HasPrefix(strings.TrimSpace(l), "jobs=") {
			lines[i] = fmt.Sprintf("jobs = %v", on)
		}
	}
	return os.WriteFile(path, []byte(strings.Join(lines, "\n")), 0o644)
}

// enableJobs turns on River for an app `bogie new` made without --jobs. It is
// the same trick as `bogie app:update`, with Jobs standing in for the version:
// render the app once as it is (Jobs false) and once as it would be (Jobs
// true), and merge the difference into the app. Only the files --jobs
// touches ever differ between the two renders, so only those show up as
// anything but identical, and a file the user already edited (app/application.go,
// most likely) merges rather than being overwritten.
func enableJobs(root string, out io.Writer) error {
	say := func(format string, a ...any) { _, _ = fmt.Fprintf(out, format, a...) }
	settings, err := readSettings(root)
	if err != nil {
		return fmt.Errorf("enable jobs: %w", err)
	}
	current := Version()
	if settings.Version != current {
		return fmt.Errorf("enable jobs: this app is at bogie %s and this bogie is %s; run `bogie app:update` first", settings.Version, current)
	}
	if dirty, derr := gitDirty(root); derr == nil && dirty {
		return fmt.Errorf("enable jobs: the git tree has uncommitted changes; commit or stash them, since this touches several files in one diff")
	}

	render := func(jobs bool) (map[string][]byte, error) {
		dir, err := os.MkdirTemp("", "bogie-jobs-")
		if err != nil {
			return nil, err
		}
		defer func() { _ = os.RemoveAll(dir) }()
		vars := scaffold.Vars{
			Name:          settings.Name,
			Module:        settings.Module,
			EnvPrefix:     strings.ToUpper(settings.Name),
			LayoutVersion: current,
			Jobs:          jobs,
			IDScheme:      string(settings.IDScheme),
			Mascot:        templates.MascotDataURI(),
		}
		if _, err := scaffold.Render(templates.App, "app", dir, vars, scaffold.Options{}); err != nil {
			return nil, err
		}
		return readTree(dir)
	}
	base, err := render(false)
	if err != nil {
		return fmt.Errorf("enable jobs: render: %w", err)
	}
	theirs, err := render(true)
	if err != nil {
		return fmt.Errorf("enable jobs: render: %w", err)
	}
	// Two of theirs's lines land at an anchor another generator also writes
	// to: the next import after app/controllers, and the command map above
	// bogie:commands, which gofmt column-aligns, so even an untouched entry's
	// spacing shifts once a longer key joins. A blind 3-way merge cannot tell
	// two independent insertions apart there, so those two lines are
	// stripped out of theirs before merging and added back afterwards
	// through the same marker mechanism every other generator uses for
	// exactly this.
	jobsImport := settings.Module + "/app/jobs"
	jobsCommand := `"worker": runWorker,`
	if src, ok := theirs["app/application.go"]; ok {
		out, _ := markers.Remove(src, fmt.Sprintf("%q", jobsImport))
		theirs["app/application.go"] = out
	}
	if src, ok := theirs["main.go"]; ok {
		out, changed := markers.Remove(src, jobsCommand)
		if changed {
			if out, err = markers.Format(out); err != nil {
				return fmt.Errorf("enable jobs: %w", err)
			}
		}
		theirs["main.go"] = out
	}
	ours, err := readTree(root)
	if err != nil {
		return err
	}
	results, err := merge(ours, base, theirs, "without jobs", "with jobs")
	if err != nil {
		return fmt.Errorf("enable jobs: %w", err)
	}

	conflicts := 0
	for _, r := range results {
		if r.op == opIdentical {
			continue // most files: nothing --jobs touches
		}
		say("%12s  %s\n", r.op, r.path)
		if r.op == opConflict {
			conflicts++
		}
		if r.content == nil {
			continue
		}
		abs := filepath.Join(root, filepath.FromSlash(r.path))
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			return err
		}
		mode := os.FileMode(0o644)
		if strings.HasPrefix(r.path, "bin/") {
			mode = 0o755
		}
		if err := os.WriteFile(abs, r.content, mode); err != nil {
			return err
		}
	}
	if conflicts > 0 {
		return fmt.Errorf("enable jobs: %d conflict(s); resolve them, then run bogie doctor and bin/ci", conflicts)
	}

	// The two lines stripped out above go back in now, the same way `g
	// controller` or `g authentication` would have added them: one marker
	// insert, one import, into whatever is on disk now, next to anything
	// another generator put there.
	report := func(a scaffold.Action) { say("%12s  %s\n", a.Op, a.Path) }
	if err := wire(root, []generate.Wire{{File: "main.go", Marker: "commands", Line: jobsCommand}}, nil, false, report); err != nil {
		return fmt.Errorf("enable jobs: %w", err)
	}
	appGo := filepath.Join(root, "app", "application.go")
	src, err := os.ReadFile(appGo)
	if err != nil {
		return err
	}
	if out, changed, aerr := markers.AddImport(src, jobsImport); aerr != nil {
		return fmt.Errorf("enable jobs: %w", aerr)
	} else if changed {
		if out, err = markers.Format(out); err != nil {
			return fmt.Errorf("enable jobs: %w", err)
		}
		if err := os.WriteFile(appGo, out, 0o644); err != nil {
			return err
		}
		say("%12s  app/application.go: import %q\n", "insert", jobsImport)
	}

	if err := rewriteJobs(root, true); err != nil {
		return err
	}
	say("%12s  %s: jobs = true\n", "updated", Marker)
	say("%12s  go mod tidy\n", "run")
	if err := goIn(root, out, "mod", "tidy"); err != nil {
		return fmt.Errorf("enable jobs: go mod tidy: %w", err)
	}
	return nil
}

// goIn runs a go command in the app.
func goIn(root string, out io.Writer, args ...string) error {
	cmd := exec.Command("go", args...)
	cmd.Dir = root
	cmd.Stdout = out
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

// gitDirty reports whether the app's git tree has uncommitted changes. An
// app that is not a git repository is never dirty.
func gitDirty(root string) (bool, error) {
	cmd := exec.Command("git", "status", "--porcelain")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return false, err
	}
	return len(bytes.TrimSpace(out)) > 0, nil
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

// missingTools names the tool directives this version's go.mod template
// carries that the app's go.mod does not. Order follows the template, so the
// report reads the way the file does.
func missingTools(template []byte, root string) []string {
	have, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil
	}
	var missing []string
	for _, tool := range toolDirectives(template) {
		if !strings.Contains(string(have), tool) {
			missing = append(missing, tool)
		}
	}
	return missing
}

// toolDirectives reads the module paths under a go.mod's tool directive, in
// either form: a parenthesised block, or one `tool path` line.
func toolDirectives(src []byte) []string {
	var tools []string
	inBlock := false
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		switch {
		case line == "" || strings.HasPrefix(line, "//"):
			continue
		case inBlock && line == ")":
			inBlock = false
		case inBlock:
			tools = append(tools, line)
		case line == "tool (":
			inBlock = true
		case strings.HasPrefix(line, "tool "):
			tools = append(tools, strings.TrimSpace(strings.TrimPrefix(line, "tool ")))
		}
	}
	return tools
}

// bogieModules are the requirements app:update raises to the template's
// version when the app's is older: modules Bogie publishes, whose API the
// templated code calls.
var bogieModules = []string{"github.com/bogie-go/credentials"}

// staleBogieModules returns "module@version" for each of bogieModules that the
// template requires at a newer version than the app's go.mod does. A module
// the app does not require at all is left to go mod tidy.
func staleBogieModules(template []byte, root string) []string {
	have, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil
	}
	want, got := requiredVersions(template), requiredVersions(have)
	var stale []string
	for _, mod := range bogieModules {
		if w, ok := want[mod]; ok {
			if g, ok := got[mod]; ok && semverLess(g, w) {
				stale = append(stale, mod+"@"+w)
			}
		}
	}
	return stale
}

// requiredVersions reads module -> version from the require lines of a
// go.mod, in either the block or the one-line form.
func requiredVersions(src []byte) map[string]string {
	out := map[string]string{}
	inBlock := false
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		switch {
		case line == "" || strings.HasPrefix(line, "//"):
			continue
		case inBlock && line == ")":
			inBlock = false
			continue
		case line == "require (":
			inBlock = true
			continue
		case strings.HasPrefix(line, "require "):
			line = strings.TrimSpace(strings.TrimPrefix(line, "require "))
		case !inBlock:
			continue
		}
		if f := strings.Fields(line); len(f) >= 2 {
			out[f[0]] = f[1]
		}
	}
	return out
}

// semverLess reports whether vA is an older release than vB, comparing
// vMAJOR.MINOR.PATCH numerically. A version it cannot parse is never older.
func semverLess(a, b string) bool {
	pa, okA := semverParts(a)
	pb, okB := semverParts(b)
	if !okA || !okB {
		return false
	}
	for i := range pa {
		if pa[i] != pb[i] {
			return pa[i] < pb[i]
		}
	}
	return false
}

func semverParts(v string) ([3]int, bool) {
	var p [3]int
	v = strings.TrimPrefix(v, "v")
	if i := strings.IndexAny(v, "-+"); i >= 0 {
		v = v[:i]
	}
	f := strings.Split(v, ".")
	if len(f) != 3 {
		return p, false
	}
	for i, s := range f {
		n, err := strconv.Atoi(s)
		if err != nil {
			return p, false
		}
		p[i] = n
	}
	return p, true
}
